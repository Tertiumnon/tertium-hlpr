import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { createInterface } from 'node:readline/promises'
import { askWith, collectDeployConfig } from '../deploy/config.js'
import { type DeployConfig, buildGithubDeployYaml } from '../deploy/deploy.js'
import { type PackageJson, type PackageManager, RUN_PREFIX, detectPackageManager, isTypeScriptProject, readPackageJson } from '../npm/project.js'

export const WORKFLOW_NAMES = ['publish', 'deploy'] as const
export type WorkflowName = (typeof WORKFLOW_NAMES)[number]

const INSTALL_COMMAND: Record<PackageManager, string> = {
  bun: 'bun install --frozen-lockfile',
  pnpm: 'pnpm install --frozen-lockfile',
  yarn: 'yarn install --frozen-lockfile',
  npm: 'npm ci',
}

// Trusted publishing (OIDC) is an npm CLI feature, so the publish step always runs through
// `npm publish` regardless of which package manager built/tested the project.
const TOOLCHAIN_SETUP_STEP: Record<PackageManager, string> = {
  bun: '      - name: Setup Bun\n        uses: oven-sh/setup-bun@v2\n\n',
  pnpm: '      - name: Setup pnpm\n        uses: pnpm/action-setup@v6\n\n',
  yarn: '',
  npm: '',
}

function stepLine(manager: PackageManager, script: string, name: string): string {
  return `      - name: ${name}\n        run: ${RUN_PREFIX[manager]} ${script}\n\n`
}

function optionalStep(manager: PackageManager, pkg: PackageJson, script: string, name: string): string {
  return pkg.scripts?.[script] ? stepLine(manager, script, name) : ''
}

// TypeScript projects always get lint and typecheck steps, so a missing script fails CI loudly.
// build and test are included only when the project defines them.
export function buildPublishWorkflow(pkg: PackageJson, manager: PackageManager, isTypeScript: boolean): string {
  const lintStep = isTypeScript ? stepLine(manager, 'lint', 'Lint') : optionalStep(manager, pkg, 'lint', 'Lint')
  const typecheckStep = isTypeScript ? stepLine(manager, 'typecheck', 'Typecheck') : ''
  const buildStep = optionalStep(manager, pkg, 'build', 'Build')
  const testStep = optionalStep(manager, pkg, 'test', 'Test')

  return `# Generated by hlpr gh setup -workflow publish - https://docs.npmjs.com/trusted-publishers
name: Publish to npm

on:
  push:
    tags:
      - "v*"
  workflow_dispatch:

permissions:
  contents: read
  id-token: write

jobs:
  publish:
    runs-on: ubuntu-latest
    steps:
      - name: Checkout
        uses: actions/checkout@v7

      - name: Setup Node
        uses: actions/setup-node@v7
        with:
          node-version: "lts/*"
          registry-url: "https://registry.npmjs.org"

      - name: Ensure npm supports trusted publishing
        run: npm install -g npm@latest

${TOOLCHAIN_SETUP_STEP[manager]}      - name: Install dependencies
        run: ${INSTALL_COMMAND[manager]}

${lintStep}${typecheckStep}${buildStep}${testStep}      - name: Publish
        run: npm publish
`
}

export function setupPublishWorkflow(projectPath: string, options: { force?: boolean } = {}): void {
  const pkg = readPackageJson(projectPath)
  if (pkg.private && !options.force) {
    throw new Error(`${pkg.name ?? 'This package'} is marked "private": true. Trusted publishing does not apply to packages that are never published. Remove "private" first, or pass -force.`)
  }

  const workflowDir = path.join(projectPath, '.github', 'workflows')
  const workflowPath = path.join(workflowDir, 'publish.yml')
  if (existsSync(workflowPath) && !options.force) throw new Error(`${workflowPath} already exists. Pass -force to overwrite it.`)

  const manager = detectPackageManager(projectPath)
  const isTypeScript = isTypeScriptProject(projectPath, pkg)

  mkdirSync(workflowDir, { recursive: true })
  writeFileSync(workflowPath, buildPublishWorkflow(pkg, manager, isTypeScript))

  console.log(`✅ Wrote ${workflowPath} (package manager: ${manager}${isTypeScript ? ', TypeScript' : ''})`)
  console.log(`
📋 One-time setup still required on npmjs.com before this works:
   1. Go to https://www.npmjs.com/package/${pkg.name ?? '<your-package>'}/access
   2. Under "Trusted Publisher", add a GitHub Actions publisher:
      - Organization or user: <your GitHub org/user>
      - Repository: <this repo's name>
      - Workflow filename: publish.yml
      - Environment name: (leave blank unless you added one)
      - Allowed actions: also enable "npm publish", not just the default
        "npm stage publish" - otherwise the publish step fails with
        "403 OIDC permission denied for this action"
   3. No NPM_TOKEN secret is needed - the workflow authenticates via OIDC.

Trigger: push a "v*" tag (e.g. \`npm version patch && git push --tags\`) or run the workflow manually.
`)
}

export async function setupDeployWorkflow(projectPath: string, options: { force?: boolean } = {}): Promise<void> {
  const workflowDir = path.join(projectPath, '.github', 'workflows')
  const workflowPath = path.join(workflowDir, 'deploy.yml')
  if (existsSync(workflowPath) && !options.force) throw new Error(`${workflowPath} already exists. Pass -force to overwrite it.`)

  const rl = createInterface({ input: process.stdin, output: process.stdout })
  let config: DeployConfig
  try {
    console.log('\n🚀 GitHub Deployment Workflow Setup\n')
    config = await collectDeployConfig(askWith(rl), projectPath, { withSsh: false })
  } finally {
    rl.close()
  }

  mkdirSync(workflowDir, { recursive: true })
  writeFileSync(workflowPath, buildGithubDeployYaml(config))

  console.log(`
✅ Wrote ${workflowPath}

📋 Configuration:
   - Project: ${config.projectName}
   - Environment: ${config.environment} (GitHub environment of the same name)
   - Deploy path: ${config.deployPath}
   - App name: ${config.appName ?? '(static site)'}
   - Prisma: ${config.hasPrisma ? 'yes' : 'no'}

📌 One-time setup required:
   1. GitHub → Settings → Environments → create "${config.environment}"
   2. Add environment secrets: SSH_HOST (production server), SSH_USER (deployment user),
      SSH_PRIVATE_KEY (PEM private key whose public half is in the server's ~/.ssh/authorized_keys)
   3. On the production server, make ${config.deployPath} a git clone of the repository (with read
      access to it) and create .env.

🚀 To deploy: npm run release:patch (pushes a v* tag, which triggers the workflow)
`)
}
