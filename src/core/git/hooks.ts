import { execFileSync } from 'node:child_process'
import { chmodSync, existsSync, mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { type PackageJson, type PackageManager, RUN_PREFIX, detectPackageManager, isTypeScriptProject, readPackageJson } from '../npm/project.js'

export const HOOKS_DIR = '.githooks'
export const HOOKS_PATH_COMMAND = `git config core.hooksPath ${HOOKS_DIR}`
const HOOK_NAME = 'pre-commit'

function checkBlock(manager: PackageManager, script: string, label: string): string {
  return `echo "▶ ${label}"\n${RUN_PREFIX[manager]} ${script}\n\n`
}

// TypeScript projects always get lint and typecheck, so a missing script fails the commit
// loudly instead of skipping the check. "test" runs only when the project defines it.
export function buildPreCommitHook(pkg: PackageJson, manager: PackageManager, isTypeScript: boolean): string {
  const checks = [
    isTypeScript || pkg.scripts?.lint ? checkBlock(manager, 'lint', 'Lint') : '',
    isTypeScript || pkg.scripts?.typecheck ? checkBlock(manager, 'typecheck', 'Typecheck') : '',
    pkg.scripts?.test ? checkBlock(manager, 'test', 'Test') : '',
  ].join('')

  return `#!/usr/bin/env sh
# Generated by hlpr - runs on every commit via core.hooksPath
set -e

${checks}`
}

export function setupGitHooks(projectPath: string, options: { force?: boolean } = {}): void {
  if (!existsSync(path.join(projectPath, '.git'))) throw new Error(`Not a git repository (no .git found): ${projectPath}`)

  const pkg = readPackageJson(projectPath)
  const hookPath = path.join(projectPath, HOOKS_DIR, HOOK_NAME)
  if (existsSync(hookPath) && !options.force) throw new Error(`${hookPath} already exists. Pass --force to overwrite it.`)

  const manager = detectPackageManager(projectPath)
  const isTypeScript = isTypeScriptProject(projectPath, pkg)

  mkdirSync(path.dirname(hookPath), { recursive: true })
  writeFileSync(hookPath, buildPreCommitHook(pkg, manager, isTypeScript))
  try {
    chmodSync(hookPath, 0o755)
  } catch {
    // Windows has no POSIX mode bits; Git for Windows still runs the hook through its shebang.
  }

  execFileSync('git', ['config', 'core.hooksPath', HOOKS_DIR], { cwd: projectPath, stdio: 'inherit' })

  if (pkg.scripts?.prepare !== HOOKS_PATH_COMMAND) {
    pkg.scripts = { ...pkg.scripts, prepare: HOOKS_PATH_COMMAND }
    writeFileSync(path.join(projectPath, 'package.json'), `${JSON.stringify(pkg, null, 2)}\n`)
    console.log(`✏️  Added "prepare" → "${HOOKS_PATH_COMMAND}" to package.json`)
  }

  console.log(`✅ Wrote ${hookPath} and set core.hooksPath (package manager: ${manager}${isTypeScript ? ', TypeScript' : ''})`)
}
