export interface DeployConfig {
  projectName: string
  environment: string
  deployPath: string
  hasPrisma: boolean
  appName?: string
  sshEndpoint?: string
}

const SSH_COMMAND_BASE = `
set -e
export PATH="$HOME/.bun/bin:$PATH"
`

const DEPLOYMENT_COMMANDS = {
  gitSync: 'git fetch origin main 2>&1 && git reset --hard origin/main 2>&1',
  envSource: 'set -a && [ -f .env ] && source .env 2>&1 && set +a',
  bunInstall: (production: boolean) => `bun install${production ? ' --production' : ''} 2>&1`,
  prismaGenerate: 'bunx prisma generate --schema=prisma/schema.prisma 2>&1',
  prismaMigrate: 'bunx prisma migrate deploy --schema=prisma/schema.prisma 2>&1',
  bunBuild: 'bun run build 2>&1',
  pm2Restart: (appName: string) => `pm2 restart ${appName} || pm2 start pm2.config.cjs 2>&1 && pm2 save`,
}

export function buildSshCommands(config: DeployConfig): string[] {
  const commands = [`cd ${config.deployPath}`, DEPLOYMENT_COMMANDS.gitSync, DEPLOYMENT_COMMANDS.envSource, DEPLOYMENT_COMMANDS.bunInstall(config.hasPrisma)]
  if (config.hasPrisma) commands.push(DEPLOYMENT_COMMANDS.prismaGenerate, DEPLOYMENT_COMMANDS.prismaMigrate)
  if (!config.hasPrisma) commands.push(DEPLOYMENT_COMMANDS.bunBuild)
  if (config.hasPrisma && config.appName) commands.push(DEPLOYMENT_COMMANDS.pm2Restart(config.appName))
  return commands
}

export function buildDeployScript(config: DeployConfig): string {
  return SSH_COMMAND_BASE + buildSshCommands(config).map(cmd => cmd.trim()).join('\n')
}

// Indents a multi-line script for a YAML block scalar; blank lines stay empty.
function indentBlock(text: string, spaces: number): string {
  return text
    .split('\n')
    .map(line => (line.trim() ? `${' '.repeat(spaces)}${line}` : ''))
    .join('\n')
}

export function buildAzureYaml(config: DeployConfig): string {
  if (!config.sshEndpoint) throw new Error('Azure pipelines need an SSH service connection name')
  return `trigger:
  tags:
    include:
      - v*

pool:
  vmImage: 'ubuntu-latest'

steps:
  - task: SSH@0
    inputs:
      sshEndpoint: '${config.sshEndpoint}'
      runOptions: 'inline'
      inline: |
${indentBlock(buildDeployScript(config), 8)}
`
}

// GitHub Actions has no SSH service connections, so the server details come from
// environment secrets: SSH_HOST, SSH_USER and SSH_PRIVATE_KEY in the GitHub environment.
export function buildGithubDeployYaml(config: DeployConfig): string {
  return `# Generated by hlpr gh setup -workflow deploy
name: Deploy to ${config.environment}

on:
  push:
    tags:
      - "v*"
  workflow_dispatch:

permissions:
  contents: read

jobs:
  deploy:
    runs-on: ubuntu-latest
    environment: ${config.environment}
    steps:
      - name: Deploy over SSH
        uses: appleboy/ssh-action@v1.2.0
        with:
          host: \${{ secrets.SSH_HOST }}
          username: \${{ secrets.SSH_USER }}
          key: \${{ secrets.SSH_PRIVATE_KEY }}
          script: |
${indentBlock(buildDeployScript(config).trim(), 12)}
`
}
